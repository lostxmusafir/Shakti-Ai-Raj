from typing import List, Optional, Any, Union, Dict
from pydantic import BaseModel, Field

class Condition(BaseModel):
    column: str
    operator: str  # equals, not_equals, greater_than, less_than, greater_than_or_equal, less_than_or_equal, in, not_in, contains, not_contains, is_null, is_not_null
    value: Optional[Any] = None

class AggregateOperation(BaseModel):
    column: Optional[str] = None  # None or "*" for count
    function: str  # count, sum, avg, min, max, median, count_distinct, count_nonzero
    alias: Optional[str] = None
    distinct: bool = False
    filter_condition: Optional[Union[Condition, str]] = None

class SortRule(BaseModel):
    column: str
    ascending: bool = True

class JoinRule(BaseModel):
    left_dataset: str
    right_dataset: str
    left_column: str
    right_column: str
    join_type: str = "inner"  # inner, left, right, outer, anti, semi

class DatasetRef(BaseModel):
    file_id: str
    alias: str

class AnalysisPlan(BaseModel):
    intent: str = "DATA_ANALYSIS"
    question: str
    datasets: List[DatasetRef]
    filters: List[Condition] = Field(default_factory=list)
    group_by: List[str] = Field(default_factory=list)
    aggregations: List[AggregateOperation] = Field(default_factory=list)
    having: List[Condition] = Field(default_factory=list)
    sort: List[SortRule] = Field(default_factory=list)
    limit: Optional[int] = 100
    joins: List[JoinRule] = Field(default_factory=list)
    requires_policy: bool = False
    policy_code: Optional[str] = None
    sql_query: Optional[str] = None  # Direct SQL generated by AI planner or compiler
    skills: List[str] = Field(default_factory=list)
    result_shape: Optional[str] = None  # scalar_metric, two_metrics, multi_metric, grouped_rows, ranked_rows
    requested_concepts: List[str] = Field(default_factory=list)
    record_family: Optional[str] = None  # Bound logical record family in mixed datasets
    resolved_bindings: List[Dict[str, Any]] = Field(default_factory=list)
